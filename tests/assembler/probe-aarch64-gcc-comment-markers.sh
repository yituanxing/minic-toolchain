#!/usr/bin/env bash
# GNU GCC saves preprocessed .S source with leading ### comments. They are
# whole-line comments; AArch64 #42 operands must remain ordinary immediates.
set -Eeuo pipefail

repo=$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
minias=${MINIAS:-"$repo/build/release/bin/minic-as"}
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT

printf '%s\n' '.text' '### Generated by GNU Kbuild ###' \
    'mov x0, #42' 'ret' >"$work/valid.s"
"$minias" --target=aarch64 -march=armv8-a -mabi=lp64 \
    -o "$work/valid.o" "$work/valid.s"
readelf -x .text "$work/valid.o" >"$work/hex.txt"
grep -qi '400580d2 c0035fd6' "$work/hex.txt"

# A source line consisting solely of #42 is not a preprocessor comment or
# GCC marker. Reject it instead of silently dropping an unknown instruction.
printf '%s\n' '.text' '#42' 'ret' >"$work/invalid.s"
if "$minias" --target=aarch64 -march=armv8-a -mabi=lp64 \
     -o "$work/invalid.o" "$work/invalid.s" >"$work/negative.log" 2>&1; then
    echo 'AARCH64_GCC_COMMENTS=FAIL accepted #42 as a source comment' >&2
    exit 1
fi
echo 'AARCH64_GCC_COMMENTS=PASS generated_marker=1 immediate=42 invalid=1'
